"""Generate lib/data/sellwood_addresses.dart from the prototype map extract."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'docs/design/prototype/solum-map-data.js'
OUT = ROOT / 'lib/data/sellwood_addresses.dart'

# lon = AX * x + BX ; lat = AY * y + BY  (fit against OSM address buildings)
AX, BX = 1.0398961595097303e-05, -122.65819767562407
AY, BY = -7.295738461342727e-06, 45.47029999690182


def ll(x, y):
    return round(AY * y + BY, 7), round(AX * x + BX, 7)


def main():
    s = SRC.read_text()
    d = json.loads(s[s.index('{'):s.rindex('}') + 1])
    seen, rows = set(), []
    for x, y, street in d['addrs']:
        if street in seen:
            continue
        seen.add(street)
        lat, lng = ll(x, y)
        rows.append(f"  MapAddress('{street}', {lat}, {lng}),")
    OUT.write_text(
        '// GENERATED by tool/gen_sellwood_data.py. Do not edit by hand.\n'
        '// Address points: © OpenStreetMap contributors (ODbL). Sellwood, Portland OR.\n'
        "import 'models.dart';\n\n"
        '/// Street addresses in the bundled Sellwood extract. Production swaps this\n'
        '/// for a geocoding source behind [AddressRepository].\n'
        'const sellwoodAddresses = <MapAddress>[\n' + '\n'.join(rows) + '\n];\n')
    print(f'{len(rows)} addresses -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
